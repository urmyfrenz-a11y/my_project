/** 텍스트로 업종을 판정. 특정 업종 신호가 없으면 '전업종'. */
export function classifyIndustry(...texts: (string | null | undefined)[]): Industry {
  const hay = texts.filter(Boolean).join(" ");
  if (!hay.trim()) return DEFAULT_INDUSTRY;
  for (const rule of RULES) {
    if (rule.re.test(hay)) return rule.name;
  }
  return DEFAULT_INDUSTRY;
}
